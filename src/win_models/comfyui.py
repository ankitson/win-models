def venv_python(comfy_home: Path) -> Path:
    python = comfy_home / ".venv" / "Scripts" / "python.exe"
    if not python.exists():
        raise FileNotFoundError(
            f"Missing ComfyUI venv at {python}. Run: just comfy setup"
        )
    return python


def ensure_comfy_repo(comfy_home: Path, *, update: bool = False) -> None:
    if (comfy_home / ".git").exists():
        if update:
            run(["git", "-C", comfy_home, "pull", "--ff-only"])
        else:
            echo(f"ComfyUI repo already present: {comfy_home}")
        return

    if comfy_home.exists() and any(comfy_home.iterdir()):
        raise FileExistsError(
            f"{comfy_home} exists but is not a git checkout. Move it aside or set COMFYUI_HOME."
        )

    ensure_dir(comfy_home.parent)
    run(["git", "clone", REPO_URL, comfy_home])


def write_extra_model_paths(comfy_home: Path, model_root: Path) -> Path:
    ensure_dir(model_root)
    for subdir in MODEL_SUBDIRS:
        ensure_dir(model_root / subdir)

    config = comfy_home / "extra_model_paths.yaml"
    lines = [
        "# Generated by win-models. Keep shared diffusion assets under COMFYUI_MODEL_ROOT.",
        "win_models:",
        f"    base_path: {model_root}",
        "    is_default: true",
    ]
    for subdir in MODEL_SUBDIRS:
        lines.append(f"    {subdir}: {subdir}")
    config.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    echo(f"Wrote {config}")
    return config


def install_prompt_logger_node(comfy_home: Path) -> Path:
    if not PROMPT_LOGGER_SOURCE.exists():
        raise FileNotFoundError(f"Missing prompt logger source: {PROMPT_LOGGER_SOURCE}")
    target = comfy_home / "custom_nodes" / "win_models_prompt_logger.py"
    ensure_dir(target.parent)
    target.write_text(PROMPT_LOGGER_SOURCE.read_text(encoding="utf-8"), encoding="utf-8", newline="\n")
    return target


def install_workflow_templates_node(comfy_home: Path) -> Path:
    if not WORKFLOW_TEMPLATES_SOURCE.exists():
        raise FileNotFoundError(f"Missing workflow templates source: {WORKFLOW_TEMPLATES_SOURCE}")
    target = comfy_home / "custom_nodes" / "win_models_templates"
    if target.exists():
        shutil.rmtree(target)
    shutil.copytree(WORKFLOW_TEMPLATES_SOURCE, target)
    return target


def tee_process_output(
    args: list[str | os.PathLike[str]],
    *,
    cwd: Path,
    env: dict[str, str],
    stdout_log: Path,
    stderr_log: Path,
) -> None:
    printable = " ".join(str(a) for a in args)
    echo(f"> {printable}")
    ensure_dir(stdout_log.parent)
    ensure_dir(stderr_log.parent)
    header = f"\n\n--- ComfyUI started {time.strftime('%Y-%m-%d %H:%M:%S')} ---\n".encode("utf-8")

    with stdout_log.open("ab", buffering=0) as out_file, stderr_log.open("ab", buffering=0) as err_file:
        out_file.write(header)
        err_file.write(header)
        process = subprocess.Popen(
            [str(a) for a in args],
            cwd=cwd,
            env=env,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
        )

        def pump(pipe: Any, log_file: Any) -> None:
            try:
                while True:
                    chunk = pipe.read(4096)
                    if not chunk:
                        break
                    log_file.write(chunk)
            finally:
                pipe.close()

        threads = [
            threading.Thread(target=pump, args=(process.stdout, out_file), daemon=True),
            threading.Thread(target=pump, args=(process.stderr, err_file), daemon=True),
        ]
        for thread in threads:
            thread.start()
        return_code = process.wait()
        for thread in threads:
            thread.join()
    if return_code != 0:
        raise SystemExit(return_code)


def env_truthy(name: str, default: bool) -> bool:
    value = os.environ.get(name)
    if value is None:
        return default
    return value.lower() in {"1", "true", "yes", "on"}


def pip_install(python: Path, packages: list[str], extra_args: list[str] | None = None) -> None:
    command: list[str | os.PathLike[str]] = [
        "uv",
        "pip",
        "install",
        "--python",
        python,
        "--link-mode",
        "copy",
        "--upgrade",
    ]
    command.extend(packages)
    if extra_args:
        command.extend(extra_args)
    run(command)


def install_dependencies(args: argparse.Namespace, python: Path, comfy_home: Path) -> None:
    if args.torch != "skip":
        if args.torch == "nvidia":
            pip_install(
                python,
                ["torch", "torchvision", "torchaudio"],
                ["--extra-index-url", args.torch_index_url],
            )
        elif args.torch == "cpu":
            pip_install(python, ["torch", "torchvision", "torchaudio"])
        else:
            raise ValueError(f"Unsupported torch install mode: {args.torch}")

    requirements = comfy_home / "requirements.txt"
    if not requirements.exists():
        raise FileNotFoundError(f"Missing {requirements}")
    run(
        [
            "uv",
            "pip",
            "install",
            "--python",
            python,
            "--link-mode",
            "copy",
            "--upgrade",
            "-r",
            requirements,
        ]
    )


def setup(args: argparse.Namespace) -> None:
    comfy_home = Path(args.comfy_home)
    model_root = Path(args.model_root)
    echo("=== ComfyUI setup ===")
    echo(f"ComfyHome={comfy_home}  ModelRoot={model_root}")

    ensure_comfy_repo(comfy_home, update=args.update)
    if not (comfy_home / ".venv").exists() or args.recreate_venv:
        if args.recreate_venv and (comfy_home / ".venv").exists():
            raise RuntimeError(
                "Refusing to delete an existing venv automatically. "
                "Remove it manually, then re-run setup."
            )
        run(["uv", "venv", "--python", args.python, comfy_home / ".venv"])

    python = venv_python(comfy_home)
    install_dependencies(args, python, comfy_home)
    write_extra_model_paths(comfy_home, model_root)
    prompt_logger = install_prompt_logger_node(comfy_home)
    echo(f"Installed prompt logger custom node: {prompt_logger}")
    templates = install_workflow_templates_node(comfy_home)
    echo(f"Installed workflow templates custom node: {templates}")
    ensure_runtime_dirs(args)
    echo("\nDone. Launch with: just comfy serve")


